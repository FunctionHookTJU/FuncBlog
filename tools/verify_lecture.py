#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""讲义构建产物验证（只读，不写文件）。不靠肉眼看截图，全部用计数与正则判定。

用法（仓库根目录）：
    python tools/verify_lecture.py                    # 校验全部讲义
    python tools/verify_lecture.py quantum-foundations

判定项：
  A 交付完整性：每节页面 + index.html + 跳转页都存在，无“尚未撰写”占位
  B 标签闭合：div / table / tr / td / th / pre / code / blockquote / mark / span / aside / nav
  C Markdown 残留：**、|---|、@@MATH
  D 公式：无残留 \\( \\) 定界符；.katex-error 为 0；公式数与正文规模匹配
  E 链接：侧栏 / 分页器 / 正文内部 .html 链接全部可达；index 覆盖全部小节
  F 体积：单页 > 400KB 报警（用户核心诉求：单页不能大到无法渲染）
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAIRS = ["div", "table", "tr", "td", "th", "pre", "code", "blockquote", "mark", "span", "aside", "nav", "ul", "li"]
# 体积阈值由实测校准（tools/verify_browser.mjs = headless Chrome + CDP，非猜测）：
#   682KB / 251 条公式 / 17364 个 DOM 节点 → loadEventEnd 368ms
#   677KB → 672ms，203KB → 188ms，index 约 20KB → 60~85ms，强制完整布局 < 0.2ms
# 因此：>700KB 仅提示；>900KB 才判为可能难以渲染（该拆节，或改用 output:"html" 去掉 MathML）。
WARN_PAGE_KB = 700
MAX_PAGE_KB = 900

try:  # 保证中文输出在 Windows 控制台不乱码
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
except Exception:  # pragma: no cover
    pass


def load_pages(slug):
    d = os.path.join(ROOT, "pages", slug)
    out = {}
    for fn in sorted(os.listdir(d)):
        if fn.endswith(".html"):
            out[fn] = open(os.path.join(d, fn), encoding="utf-8").read()
    return out


def check_lecture(lecture):
    slug = lecture["slug"]
    errors, warns, stats = [], [], []
    d = os.path.join(ROOT, "pages", slug)
    pages = load_pages(slug)

    # A 完整性
    expect = ["index.html"] + ["%s-%02d.html" % (slug, i) for i in range(1, len(lecture["sections"]) + 1)]
    for p in expect:
        if p not in pages:
            errors.append("缺少页面 %s" % p)
    if not os.path.exists(os.path.join(ROOT, "pages", slug + ".html")):
        errors.append("缺少跳转页 pages/%s.html" % slug)
    for p, txt in pages.items():
        if 'class="pending"' in txt:
            errors.append("%s 含“尚未撰写”占位" % p)
        if "<!-- generated by tools/build_lecture.py -->" not in txt:
            warns.append("%s 不是本构建器生成（缺少标记）" % p)

    # B 标签闭合
    for p, txt in pages.items():
        for tag in PAIRS:
            o = len(re.findall(r"<%s[\s>]" % tag, txt))
            c = len(re.findall(r"</%s>" % tag, txt))
            if o != c:
                errors.append("%s 标签 <%s> 开 %d 闭 %d" % (p, tag, o, c))

    # C Markdown 残留
    for p, txt in pages.items():
        body = re.sub(r"<pre.*?</pre>", "", txt, flags=re.S)
        body = re.sub(r"<code.*?</code>", "", body, flags=re.S)
        if "@@MATH" in txt:
            errors.append("%s 残留 @@MATH 占位符" % p)
        if re.search(r"\*\*", body):
            errors.append("%s 残留 ** 加粗标记 %d 处" % (p, len(re.findall(r"\*\*", body))))
        if re.search(r"\|\s*-{3,}\s*\|", body):
            errors.append("%s 残留 Markdown 表格分隔行" % p)
        if re.search(r"\\\(|\\\)", body):
            errors.append("%s 残留 \\( \\) 定界符（公式未预渲染）" % p)

    # D 公式
    for p, txt in pages.items():
        if p == "index.html":
            continue
        kc = len(re.findall(r'class="katex"', txt))
        ke = len(re.findall(r"katex-error", txt))
        if ke:
            errors.append("%s 有 %d 个 katex-error" % (p, ke))
        md = os.path.join(d, "src", os.path.splitext(p)[0].replace(slug + "-", "") + ".md")
        mdoc = None
        for cand in os.listdir(os.path.join(d, "src")):
            if cand.startswith("%s-" % ("qf" if slug == "quantum-foundations" else "qc")):
                num = os.path.splitext(cand)[0].split("-")[1]
                if p == "%s-%s.html" % (slug, num):
                    mdoc = os.path.join(d, "src", cand)
        if mdoc and os.path.exists(mdoc):
            src = open(mdoc, encoding="utf-8").read()
            src = re.sub(r"```.*?```", "", src, flags=re.S)
            nm = len(re.findall(r"\$\$", src)) // 2 + len(re.findall(r"(?<!\$)\$(?!\$)", re.sub(r"\$\$.+?\$\$", "", src, flags=re.S))) // 2
            if nm and kc == 0:
                errors.append("%s 源文件有公式但页面无 .katex" % p)
            if kc and nm and kc < nm:
                warns.append("%s 公式数 页面 %d < 源 %d" % (p, kc, nm))

    # E 链接
    for p, txt in pages.items():
        for href in re.findall(r'href="([^"#:]+\.html)"', txt):
            tgt = os.path.normpath(os.path.join(d, href))
            if not os.path.exists(tgt):
                errors.append("%s 链接不可达: %s" % (p, href))
    idx = pages.get("index.html", "")
    for i in range(1, len(lecture["sections"]) + 1):
        f = "%s-%02d.html" % (slug, i)
        if f not in idx:
            errors.append("index.html 未覆盖 %s" % f)
        if f not in pages.get("%s-01.html" % slug, "") and i > 1:
            pass
    # 侧栏应覆盖每一节
    body_pages = [p for p in pages if p != "index.html"]
    if body_pages:
        probe = pages["%s-01.html" % slug]
        for i in range(1, len(lecture["sections"]) + 1):
            f = "%s-%02d.html" % (slug, i)
            if f not in probe:
                errors.append("侧栏导航缺少 %s" % f)

    # F 体积
    tot = 0
    for p, txt in pages.items():
        kb = len(txt.encode("utf-8")) / 1024.0
        tot += kb
        stats.append((p, kb))
        if kb > MAX_PAGE_KB:
            errors.append("%s 体积 %.0fKB > %dKB，可能难以渲染" % (p, kb, MAX_PAGE_KB))
        elif kb > WARN_PAGE_KB:
            warns.append("%s 体积 %.0fKB > %dKB（提示级）" % (p, kb, WARN_PAGE_KB))
    stats.sort(key=lambda x: -x[1])
    return slug, errors, warns, stats, tot


def main():
    cfg = json.load(open(os.path.join(ROOT, "tools", "lectures.json"), encoding="utf-8"))
    argv = sys.argv[1:]
    lecs = [l for l in cfg["lectures"] if not argv or l["slug"] in argv]
    bad = 0
    for lec in lecs:
        slug, errors, warns, stats, tot = check_lecture(lec)
        print("=" * 72)
        print("讲义 %s：%d 页，合计 %.0f KB，最大单页 %.0f KB（%s）"
              % (slug, len(stats), tot, stats[0][1], stats[0][0]))
        print("  单页体积前 5：%s" % ", ".join("%s %.0fKB" % (p, k) for p, k in stats[:5]))
        if errors:
            bad = 1
            print("  ✗ 错误 %d 条：" % len(errors))
            for e in errors[:40]:
                print("     - %s" % e)
        else:
            print("  ✓ 以上 A–F 全部通过")
        for w in warns[:15]:
            print("  ! %s" % w)
        if len(warns) > 15:
            print("  ! ……另有 %d 条警告" % (len(warns) - 15))
    sys.exit(bad)


if __name__ == "__main__":
    main()
