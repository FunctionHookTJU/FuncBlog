# ---------------------------------------------------------------- 数学公式保护

def protect_math(text):
    """把 $$...$$ / $...$ 抽成占位符，避免被 Markdown 语法吃掉。"""
    store = []

    def grab(m, display):
        store.append((display, m.group(1).strip()))
        return "\n\n@@MATH%d@@\n\n" % (len(store) - 1) if display else "@@MATH%d@@" % (len(store) - 1)

    text = re.sub(r"\$\$(.+?)\$\$", lambda m: grab(m, True), text, flags=re.S)
    text = re.sub(r"(?<!\$)\$(?!\$)(.+?)(?<!\$)\$(?!\$)", lambda m: grab(m, False), text, flags=re.S)
    return text, store


def render_batch(node, formulas):
    """formulas: [(display, tex)] -> [(ok, html_or_error)]"""
    if not formulas:
        return []
    tmp = tempfile.mkdtemp(prefix="jysmath-")
    try:
        inp = os.path.join(tmp, "in.json")
        outp = os.path.join(tmp, "out.json")
        payload = [{"tex": tex, "display": bool(disp)} for disp, tex in formulas]
        with open(inp, "w", encoding="utf-8") as f:
            json.dump(payload, f, ensure_ascii=False)
        script = os.path.join(ROOT, "tools", "render_katex.js")
        proc = subprocess.run([node, script, inp, outp], capture_output=True, text=True, encoding="utf-8")
        if proc.returncode != 0:
            sys.exit("KaTeX 渲染子进程失败: %s%s" % (proc.stdout, proc.stderr))
        with open(outp, encoding="utf-8") as f:
            return json.load(f)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def restore_math(body, store, rendered, errors):
    """把占位符替换成预渲染好的 KaTeX HTML。"""
    for i, (display, tex) in enumerate(store):
        res = rendered[i] if i < len(rendered) else {"ok": False, "error": "missing"}
        if not res.get("ok"):
            errors.append((tex, res.get("error", "?")))
            continue
        inner = res["html"]
        if display:
            lit = "\\[%s\\]" % tex
            repl = '<div class="jysmath jysmath-display">%s</div>' % inner
        else:
            lit = "\\\\(%s\\\\)" % tex
            repl = '<span class="jysmath">%s</span>' % inner
        # 独立成段的 display 公式：<p>@@MATHn@@</p> 整体替换成 <div>
        if display:
            body, n = re.subn(r"<p>\s*@@MATH%d@@\s*</p>" % i, lambda m: repl, body)
            if n:
                continue
        body = body.replace("@@MATH%d@@" % i, repl)
        if "@@MATH%d@@" % i in body:  # pragma: no cover
            errors.append((tex, "placeholder not consumed"))
    # 兜底：内联残余占位符不应存在
    left = re.findall(r"@@MATH\d+@@", body)
    if left:  # pragma: no cover
        errors.append((" ".join(left), "未消费的数学占位符"))
    return body


def body_tokens(body):
    """Markdown 转换后的讲义专用标记替换。"""
    body = body.replace("【补】", '<mark class="bubu">补</mark>')
    body = body.replace("【勘误】", '<mark class="kanwu">勘误</mark>')
    return body


def esc_title(title):
    """标题里可能含 $...$，先护住数学再转义。"""
    protected, store = protect_math(title)
    protected = html.escape(protected, quote=True)
    return protected, store


