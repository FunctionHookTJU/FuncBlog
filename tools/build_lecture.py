# ---------------------------------------------------------------- 单节转换

def normalize_bold(text):
    """把 **粗体** 预转换成 <strong>（必须在 markdown 转换之前）。

    两个实测过的原因：
    1) 裸 HTML 块（<details> 等）内部的 Markdown 不会被转换，`**` 会原样留在正文里；
    2) 中文标点旁的 `**` 会因 CommonMark 侧界定规则无法闭合，例如「（gate）**就是」——
       收尾 `**` 前面是 `）`（标点）、后面是汉字，判定为不是右界符，于是加粗失效。
    围栏代码块与行内代码内的内容受保护，不做转换。
    """
    parts = re.split(r"(```.*?```|`[^`\n]*`)", text, flags=re.S)
    for i, seg in enumerate(parts):
        if i % 2 == 0:
            parts[i] = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", seg)
    return "".join(parts)


def enable_md_in_html(text):
    """给 <details> 加 markdown="1"，否则 md_in_html 不处理其内部的表格/列表。"""
    def sub(m):
        attrs = m.group(1) or ""
        if "markdown=" in attrs:
            return m.group(0)
        return '<details%s markdown="1">' % attrs
    return re.sub(r"<details(\s[^>]*)?>", sub, text)


def convert(md_text, formulas, placeholder_errors):
    protected, store = protect_math(md_text)
    protected = normalize_bold(protected)
    protected = enable_md_in_html(protected)
    md = markdown.Markdown(extensions=["tables", "fenced_code", "attr_list", "sane_lists", "md_in_html"])
    body = md.convert(protected)
    body = body_tokens(body)
    return body, store


def build_lecture(node, lecture, only_check=False):
    slug = lecture["slug"]
    outdir = os.path.join(ROOT, "pages", slug)
    srcdir = os.path.join(outdir, "src")
    os.makedirs(srcdir, exist_ok=True)

    # 页面文件名 / 导航条目
    for i, s in enumerate(lecture["sections"], start=1):
        s["page"] = "%s-%02d.html" % (slug, i)

    # 1) 收集所有需要渲染的公式（正文 + 导航标题）
    jobs = []           # [(display, tex)]
    def add(text):
        _, store = protect_math(text)
        jobs.extend(store)
    for s in lecture["sections"]:
        p = os.path.join(srcdir, s["id"] + ".md")
        text = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
        if text:
            add(text)
        add(s["title"])
    index_path = os.path.join(ROOT, lecture["indexSrc"])
    index_text = open(index_path, encoding="utf-8").read() if os.path.exists(index_path) else ""
    if index_text:
        add(index_text)
    add(lecture["indexTitle"])

    rendered = render_batch(node, jobs)
    errors = []
    if len(rendered) != len(jobs):  # pragma: no cover
        sys.exit("KaTeX 批量渲染结果数量不匹配")

    # 2) 分配渲染结果
    cursor = 0
    navtitles = {}
    section_bodies = {}
    for s in lecture["sections"]:
        p = os.path.join(srcdir, s["id"] + ".md")
        text = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if text is not None:
            _, store = protect_math(text)
            seg = rendered[cursor:cursor + len(store)]
            cursor += len(store)
            body, store2 = convert(text, None, None)
            body = restore_math(body, store2, seg, errors)
        else:
            body = ('<div class="pending"><b>本节尚未撰写</b><br>源文件缺失：<code>%s</code>'
                    '</div>' % ("pages/%s/src/%s.md" % (slug, s["id"])))
        section_bodies[s["id"]] = body
        tprot, tstore = esc_title(s["title"])
        tseg = rendered[cursor:cursor + len(tstore)]
        cursor += len(tstore)
        navtitles[s["id"]] = restore_math(tprot, tstore, tseg, errors)

    # 3) 写每节页面
    written = []
    n = len(lecture["sections"])
    for i, s in enumerate(lecture["sections"]):
        prev = ("index.html", "目录") if i == 0 else (lecture["sections"][i - 1]["page"], navtitles[lecture["sections"][i - 1]["id"]])
        nxt = ("index.html", "回到目录") if i == n - 1 else (lecture["sections"][i + 1]["page"], navtitles[lecture["sections"][i + 1]["id"]])
        body = '<h2 id="s-1">%s</h2>\n%s' % (navtitles[s["id"]], section_bodies[s["id"]])
        prefix = shell.rel_prefix("pages/%s/%s" % (slug, s["page"]))
        page = page_shell(lecture, navtitles[s["id"]], body,
                          sidebar_html(lecture, s["id"], navtitles),
                          pager_html(prev, nxt), prefix)
        dst = os.path.join(outdir, s["page"])
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(page)
        written.append(dst)

    # 4) 写导读页
    idx_body = ""
    if index_text is not None and index_text.strip():
        _, istore = protect_math(index_text)
        seg = rendered[cursor:cursor + len(istore)]
        cursor += len(istore)
        ibody, istore2 = convert(index_text, None, None)
        box = toc_box(lecture, navtitles)
        ibody = ibody.replace("<p>[[TOC]]</p>", box).replace("[[TOC]]", box)
        # index 正文里若直接用 [[TOC]] 之外的占位符，同样还原
        istore = istore2
        ibody = restore_math(ibody, istore, seg, errors)
        idx_body = ibody
    else:
        idx_body = ('<div class="pending"><b>导读尚未撰写</b><br>源文件缺失：<code>%s</code>'
                    '</div>' % lecture["indexSrc"])
    first = lecture["sections"][0]
    idx_prefix = shell.rel_prefix("pages/%s/index.html" % slug)
    idx_page = page_shell(lecture, lecture["indexTitle"],
                          '<h2 id="s-1">%s</h2>\n%s' % (html.escape(lecture["indexTitle"]), idx_body),
                          sidebar_html(lecture, None, navtitles),
                          pager_html((idx_prefix + "pages/study.html", "学习笔记"),
                                     (first["page"], navtitles[first["id"]])),
                          idx_prefix)
    with open(os.path.join(outdir, "index.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(idx_page)

    # 5) 跳转页
    redir = """<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<title>%s</title>
<link rel="canonical" href="%s/">
<meta http-equiv="refresh" content="0; url=%s/">
<meta name="robots" content="noindex">
<style>body{margin:0;font:16px/1.8 "Segoe UI","Microsoft YaHei",sans-serif;background:#14161a;color:#e6e8ec;display:flex;min-height:100vh;align-items:center;justify-content:center}a{color:#6ea8fe}</style>
</head>
<body>
<p>正在跳转到 <a href="%s/">%s</a>…</p>
</body>
</html>
""" % (lecture["title"], slug, slug, slug, lecture["title"])
    with open(os.path.join(ROOT, "pages", slug + ".html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(redir)

    # 6) 清理陈旧页面
    valid = {s["page"] for s in lecture["sections"]} | {"index.html"}
    for fn in os.listdir(outdir):
        if fn.endswith(".html") and fn not in valid and fn.startswith(slug + "-"):
            os.remove(os.path.join(outdir, fn))

    return {"slug": slug, "sections": n, "written": written, "errors": errors,
            "missing": [s["id"] for s in lecture["sections"]
                        if not os.path.exists(os.path.join(srcdir, s["id"] + ".md"))]}


def main():
    argv = [a for a in sys.argv[1:] if not a.startswith("-")]
    cfg = json.load(open(os.path.join(ROOT, "tools", "lectures.json"), encoding="utf-8"))
    global SITE
    SITE = cfg["site"]
    node = find_node()
    lectures = cfg["lectures"]
    if argv:
        lectures = [l for l in lectures if l["slug"] in argv]
        if not lectures:
            sys.exit("没有匹配的 slug: %s" % argv)

    bad = 0
    for lec in lectures:
        r = build_lecture(node, lec)
        print("[%s] 小节 %d 个，已写 %d 个页面" % (r["slug"], r["sections"], len(r["written"])))
        if r["missing"]:
            bad = 1
            print("  缺失源文件: %s" % ", ".join(r["missing"]))
        if r["errors"]:
            bad = 1
            print("  公式渲染失败 %d 条：" % len(r["errors"]))
            for tex, err in r["errors"][:20]:
                print("    - %s  =>  %s" % (tex[:70], err[:120]))
    sys.exit(bad)


if __name__ == "__main__":
    main()
